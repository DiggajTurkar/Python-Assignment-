#20. To write a Python program to check whether a given number is an Armstrong number.
n = int(input("Enter a number: "))
temp = n
sum = 0
while temp > 0:
    digit = temp % 10
    sum += digit ** 3
    temp = temp // 10
if sum == n:
    print("Armstrong Number")
else:
    print("Not an Armstrong Number")